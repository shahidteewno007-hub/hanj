  /// Ranked values for an anime, or null when it isn't in the table.
  static Map<String, int>? forTitle(String title) =>
      _byTitle[normalise(title)];

  /// True when this anime has a ranking table at all.
  static bool covers(String title) => _byTitle.containsKey(normalise(title));

  /// Anime titles currently ranked. Handy for a debug screen.
