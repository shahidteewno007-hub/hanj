/// Hand-ranked power for anime where AniList favourites get it badly wrong.
///
/// Favourites measure fame. This table measures strength, which is the thing
/// the game claims to be about. Anything not listed here keeps its
/// favourites-derived score, so adding an anime is additive and never a
/// regression.
///
/// This is the same payload shape a Cloud Function enrichment pass would
/// return. Compiled in rather than fetched because it needs no deploy, no
/// Firestore, no runtime cost, and it works offline — and because a value
/// that never changes between app releases has no business being a network
/// call.
///
/// Values are on the same 45-99 scale as [CadreFighter.withLocalPower], so a
/// ranked and an unranked character in the same pool stay comparable.
///
/// **Matching is exact, not fuzzy.** Both the anime title and the character
/// name are normalised (lower case, letters and digits only) and then looked
/// up. Nothing is guessed, because a wrong guess would silently hand a
/// character someone else's power. That means every spelling AniList might
/// use has to be listed — hence the alias keys throughout. AniList prints
/// full names ("Edward Newgate", not "Whitebeard") and romanises
/// inconsistently ("Gojou" and "Gojo" both occur), so where there is any
/// doubt both forms point at the same value.
///
/// A series and its sequel are separate AniList entries with separate casts,
/// so several titles map to one table: Naruto and Shippuuden share a ranking
/// set, as do Bleach and the Thousand-Year Blood War.
class CadreRankings {
